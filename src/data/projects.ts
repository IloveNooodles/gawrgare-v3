export function searchProjects(query: string) {
  const term = query.toLowerCase().trim();
  return GITHUB_PROJECTS.filter(
    (project) =>
      !project.private &&
      `${project.name} ${Object.values(project.description).join(" ")} ${project.language} ${project.topics.join(" ")}`
        .toLowerCase()
        .includes(term),
  );
}
